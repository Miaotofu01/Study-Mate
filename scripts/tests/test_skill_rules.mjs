/** 这条规则的正文住在哪个技能里；没声明过就是它自己。 */
function ownerOf(skill, desc, moved = MOVED) {
  return (moved[skill] || {})[desc] || skill;
}

/** 这个技能够得着的技能：它自己 + 它加载的协议。 */
function reachable(skill) {
  return [skill, ...(REACHES[skill] || [])];
}

