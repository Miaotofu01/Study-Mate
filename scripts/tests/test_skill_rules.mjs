/* ── 适配器锚点：`replaceRequired` 的锚点必须还在它声明作用的那几份技能里 ──────
   宿主适配器把 DSH 措辞改写成宿主措辞时，锚点是「这句话」本身：正文一改，`String.replace`
   就静默空转（产物里留下 DSH 措辞），`replaceRequired` 则整份导出报错。两类都不该等到构建
   才发现。每个适配器都声明了自己作用于哪几份 skill，所以判据是**规格驱动**的：锚点必须在
   它自己声明的那几份源码里命中，而不是在随便哪一份里命中。 */
const ADAPTER_SCOPE = {
  'bin/openai-skill-compat.mjs': ['learning-system', 'record-keeping'],
  'bin/antigravity-skill-compat.mjs': ['learning-system', 'record-keeping'],
};

test('适配器锚点在它声明的 skill 里有家（没有静默空转的 replace）', () => {
  const drift = [];
  for (const [adapter, scope] of Object.entries(ADAPTER_SCOPE)) {
    const text = fs.readFileSync(path.join(ROOT, adapter), 'utf8');
    const sources = scope.map(name => SKILL_TEXT.get(name) || '');
    const anchors = [...text.matchAll(/replaceRequired\((?:result|body|\s*\n\s*result|\s*\n\s*body)?\s*,\s*\n?\s*\/((?:[^/\\\n]|\\.)+)\/([gimsuy]*)\s*,/g)]
      .map(match => ({ label: `/${match[1]}/`, re: new RegExp(match[1], match[2].includes('m') ? 'm' : '') }));
    anchors.push(...[...text.matchAll(/\.replace\(\s*\n?\s*'((?:[^'\\]|\\.){10,})'/g)]
      .map(match => ({ label: JSON.stringify(match[1]).slice(0, 48), literal: match[1] })));
    for (const anchor of anchors) {
      if (anchor.literal !== undefined && /^\{\{\w+\}\}$/.test(anchor.literal)) continue; // 角色提示模板占位符
      const hit = sources.some(source => (anchor.re ? anchor.re.test(source) : source.includes(anchor.literal)));
      if (!hit) drift.push(`${adapter} → ${anchor.label}`);
    }
  }
  assert.deepEqual(drift, [], `适配器锚点失配（正文改了、改写静默空转）：\n${drift.join('\n')}`);
});

