/* ── `.py` 一个都不许有（#80 验收第 4 条，**无条件**）────────────────────
   Python 引擎随 #83 退役，技能里不该再有 `.py`。原来这一条只覆盖 `scripts/*.py`（导出件
   那三套的判据），而 `learning-coach` 的配图那段写着 `assets/img/gen/<同名>.py`——那是**学生
   产物**的扩展名，不是引擎脚本调用，所以当时被判为「不算违规」，还反过来断言它必须在。
   但验收第 4 条写的是「技能里搜不到 `.py`」，无条件：技能正文不写死扩展名，路径的唯一出处
   是 `docs/规范/文件归属.md`（那里写的是「产图脚本」这个代称与它的落点）。

   扫的是**所有**技能正文（含 `preset/skills/**` 的 12 份），不是导出件——导出件那三套各自还有
   一条更窄的判据（`scripts/*.py`），两条不重复。 */
test('技能正文里一个 `.py` 都没有（路径的唯一出处是文件归属，技能不写扩展名）', () => {
  const offenders = [];
  for (const [name, text] of SKILL_TEXT) {
    for (const match of text.matchAll(/[\w./<>-]*\.py\b/g)) offenders.push(`${name} → ${match[0]}`);
  }
  assert.deepEqual(offenders, [], `技能正文里还有 .py（扩展名不该由技能写死）：\n${offenders.join('\n')}`);
  // 反证：判据不空转——真放一行进去必须被抓出来
  assert.equal([...'脚本落 `assets/img/gen/<同名>.py`'.matchAll(/[\w./<>-]*\.py\b/g)].length, 1);
});
