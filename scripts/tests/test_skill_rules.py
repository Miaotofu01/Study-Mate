def owner_of(skill, desc, moved=None):
    """这条规则的正文住在哪个技能里；没声明过就是它自己。"""
    return (MOVED if moved is None else moved).get(skill, {}).get(desc, skill)


def reachable(skill):
    """这个技能够得着的技能：它自己 + 它加载的协议。"""
    return [skill, *REACHES.get(skill, [])]


